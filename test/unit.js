const { makeContext } = require('./gas-mock'); const assert = require('assert');
const g = makeContext();
g.setup(); g.__props.APP_PASSWORD = 'pw';
assert.deepStrictEqual([...g.__ss.getSheets().map(s => s.getName())], ['קריאות', 'מדווחים', 'יומן שינויים']);
const t = { num: 1001, topic: 'pa', sub: 'שומעים חלש', site: '108', bldg: 'מכני', location: '=HYPERLINK("x")', priority: 2, status: 0, created: Date.now(), due: Date.now() + 1e6, log: [{ at: Date.now(), by: 'אבי', text: 'נפתחה' }] };
g.apiPut('pw', 'customers', 'c1', { name: 'דנה', phone: '0501234567' }, 'אבי');
g.apiPut('pw', 'tickets', 't1', t, 'אבי');
let r = g.apiSync('pw', 0);
assert.strictEqual(r.docs.length, 2); assert.ok(r.sheetUrl);
assert.strictEqual(r.docs.find(d => d.id === 't1').data.location, '=HYPERLINK("x")');
const cust = g.__ss.getSheetByName('מדווחים').data[1]; assert.strictEqual(cust[1], '0501234567');
const now1 = r.now;
r = g.apiSync('pw', now1 + 10000); assert.strictEqual(r.docs.length, 0, 'fast path');
g.apiPut('pw', 'tickets', 't1', { ...t, status: 1 }, 'נועה');
r = g.apiSync('pw', now1); assert.ok(r.docs.some(d => d.id === 't1' && d.data.status === 1));
assert.strictEqual(g.__ss.getSheetByName('קריאות').getLastRow(), 2, 'update in place');
g.apiDel('pw', 'tickets', 't1', 'נועה');
r = g.apiSync('pw', now1); assert.ok(r.docs.some(d => d.id === 't1' && d.deleted));
r = g.apiSync('pw', 0); assert.ok(!r.docs.some(d => d.id === 't1'));
const audit = g.__ss.getSheetByName('יומן שינויים').data.slice(1).map(x => x[1] + ':' + x[5]);
assert.deepStrictEqual([...audit], ['יצירה:אבי', 'יצירה:אבי', 'עדכון:נועה', 'מחיקה:נועה']);
g.__props.APP_PASSWORD = 'pw';
assert.strictEqual(g.apiSync('bad', 0).auth, false);
assert.ok(g.apiSync('pw', 0).docs);
const g2=makeContext();g2.setup();assert.strictEqual(g2.apiSync('', 0).setup, true, 'no password => locked');
assert.throws(() => g.apiPut('pw', 'audit', 'x', {}, ''));
assert.throws(() => g.apiPut('pw', 'tickets', 'a/b', {}, ''));
console.log('unit OK; ticket row:', JSON.stringify(g.__ss.getSheetByName('קריאות').data[1].slice(0, 12)));
